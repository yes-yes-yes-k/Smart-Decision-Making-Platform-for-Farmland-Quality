CREATE TABLE cd_flux_input_v2 (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source text NOT NULL CHECK (source IN ('native','ported','unknown')),
    parcel_id varchar(64) NOT NULL,
    sample_id varchar(64) NOT NULL,
    accounting_year integer CHECK (accounting_year BETWEEN 1 AND 9999),
    input_revision bigint NOT NULL DEFAULT 1 CHECK (input_revision > 0),
    initial_cd double precision,
    atmospheric_deposition double precision,
    irrigation_input double precision,
    agro_chemicals_input double precision,
    enterprise_input double precision,
    groundwater_leaching double precision,
    surface_runoff double precision,
    grain_removal double precision,
    straw_removal double precision,
    bulk_density_g_cm3 double precision,
    soil_depth_m double precision,
    contract_version text NOT NULL,
    provenance jsonb NOT NULL DEFAULT '{}'::jsonb,
    imported_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE NULLS NOT DISTINCT (source, parcel_id, sample_id, accounting_year)
);
CREATE TABLE cd_flux_output_v2 (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    input_id bigint NOT NULL REFERENCES cd_flux_input_v2(id),
    input_revision bigint NOT NULL,
    calculation_version text NOT NULL,
    in_cd double precision,
    out_cd double precision,
    net_cd double precision,
    end_cd double precision,
    status text NOT NULL,
    coverage jsonb NOT NULL,
    unit_status jsonb NOT NULL,
    computed_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (input_id, input_revision, calculation_version)
);
-- Finite/range/unit validation is mandatory in the shared import/calculation
-- contract before writes; draft SQL alone does not validate physical inputs.
